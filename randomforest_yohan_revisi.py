df = df.fillna(method='ffill').fillna(method='bfill')

def iqr_clip(series, k=1.5):
    q1 = series.quantile(0.25)
    q3 = series.quantile(0.75)
    iqr = q3 - q1
    return series.clip(q1 - k*iqr, q3 + k*iqr)

df['suhu'] = iqr_clip(df['suhu'])
df['kec_angin'] = iqr_clip(df['kec_angin'])

df['suhu_ma_5'] = df['suhu'].rolling(window=5).mean()
df['angin_ma_5'] = df['kec_angin'].rolling(window=5).mean()

df = df.dropna().reset_index(drop=True)

df['hour'] = df['timestamp'].dt.hour
df['hour_sin'] = np.sin(2*np.pi*df['hour']/24)
df['hour_cos'] = np.cos(2*np.pi*df['hour']/24)

df['angin_diff_1'] = df['angin_ma_5'].diff()
df['angin_diff_5'] = df['angin_ma_5'].diff(5)

df['suhu_diff_1'] = df['suhu_ma_5'].diff()
df['suhu_diff_5'] = df['suhu_ma_5'].diff(5)

df = df.dropna().reset_index(drop=True)

for w in [5, 15, 30]:
    df[f'angin_roll_mean_{w}'] = df['angin_ma_5'].rolling(w).mean()
    df[f'angin_roll_std_{w}']  = df['angin_ma_5'].rolling(w).std()

    df[f'suhu_roll_mean_{w}'] = df['suhu_ma_5'].rolling(w).mean()
    df[f'suhu_roll_std_{w}']  = df['suhu_ma_5'].rolling(w).std()

df = df.dropna().reset_index(drop=True)

LAGS = [1, 3, 5, 10, 20, 30]

for lag in LAGS:
    df[f'angin_lag_{lag}'] = df['angin_ma_5'].shift(lag)
