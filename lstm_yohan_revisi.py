import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error
from sklearn.model_selection import train_test_split

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping

plt.rcParams['figure.figsize'] = (12,5)

df = pd.read_csv("Data Monitoring Suhu & Kec Angin_Gunung Putri Lembang.csv")

df = df.rename(columns={
    "Timestamp": "timestamp",
    "Suhu (C)": "suhu",
    "Kecepatan Angin (m/s)": "kec_angin"
})

df['timestamp'] = pd.to_datetime(df['timestamp'])
df = df.sort_values('timestamp').reset_index(drop=True)

print(df.head(10))
print(df.info())

plt.figure(figsize=(14,4))
plt.plot(df['timestamp'], df['suhu'])
plt.title("Time Series Suhu")
plt.xlabel("Waktu")
plt.ylabel("Suhu (°C)")
plt.show()

plt.figure(figsize=(14,4))
plt.plot(df['timestamp'], df['kec_angin'])
plt.title("Time Series Kecepatan Angin")
plt.xlabel("Waktu")
plt.ylabel("Kecepatan Angin (m/s)")
plt.show()

df = df.fillna(method='ffill').fillna(method='bfill')

def iqr_clip(series, k=1.5):  # ← k diperkecil
    q1 = series.quantile(0.25)
    q3 = series.quantile(0.75)
    iqr = q3 - q1
    return series.clip(q1 - k*iqr, q3 + k*iqr)

df['suhu'] = iqr_clip(df['suhu'])
df['kec_angin'] = iqr_clip(df['kec_angin'])

scaler_suhu = MinMaxScaler()
scaler_angin = MinMaxScaler()

df['suhu_norm'] = scaler_suhu.fit_transform(df[['suhu']])
df['angin_norm'] = scaler_angin.fit_transform(df[['kec_angin']])

# Moving average untuk smoothing tambahan
df['suhu_ma_5'] = df['suhu_norm'].rolling(window=5).mean()
df['angin_ma_5'] = df['angin_norm'].rolling(window=5).mean()

df = df.dropna().reset_index(drop=True)

def create_lstm_sequence(data, window_size=30):  # ← TANPA horizon
    X, y = [], []
    for i in range(len(data) - window_size):
        X.append(data[i : i + window_size])
        y.append(data[i + window_size])
    return np.array(X), np.array(y)

WINDOW = 30  # ← window diperkecil

# Suhu
X_s, y_s = create_lstm_sequence(df['suhu_ma_5'].values, WINDOW)

# Angin
X_a, y_a = create_lstm_sequence(df['angin_ma_5'].values, WINDOW)

print("Shape X_s:", X_s.shape)
print("Shape y_s:", y_s.shape)

# reshape untuk LSTM
X_s = X_s.reshape((X_s.shape[0], X_s.shape[1], 1))
X_a = X_a.reshape((X_a.shape[0], X_a.shape[1], 1))

# Suhu
X_train_s, X_temp_s, y_train_s, y_temp_s = train_test_split(
    X_s, y_s, test_size=0.3, shuffle=True, random_state=42
)

X_val_s, X_test_s, y_val_s, y_test_s = train_test_split(
    X_temp_s, y_temp_s, test_size=0.5, shuffle=True, random_state=42
)

# Angin
X_train_a, X_temp_a, y_train_a, y_temp_a = train_test_split(
    X_a, y_a, test_size=0.3, shuffle=True, random_state=42
)

X_val_a, X_test_a, y_val_a, y_test_a = train_test_split(
    X_temp_a, y_temp_a, test_size=0.5, shuffle=True, random_state=42
)

model_suhu = Sequential([
    LSTM(64, return_sequences=False, input_shape=(WINDOW, 1)),
    Dropout(0.3),
    Dense(1)
])

model_suhu.compile(
    optimizer='adam',
    loss='mse'
)

model_suhu.summary()

early_stop = EarlyStopping(
    monitor='val_loss',
    patience=10,   # ← DIBESARKAN
    restore_best_weights=True
)

history_s = model_suhu.fit(
    X_train_s, y_train_s,
    validation_data=(X_val_s, y_val_s),
    epochs=100,
    batch_size=64,
    callbacks=[early_stop],
    verbose=1
)

pred_s = model_suhu.predict(X_test_s)

y_test_s_inv = scaler_suhu.inverse_transform(y_test_s.reshape(-1,1))
pred_s_inv = scaler_suhu.inverse_transform(pred_s)

mae_s = mean_absolute_error(y_test_s_inv, pred_s_inv)
rmse_s = np.sqrt(mean_squared_error(y_test_s_inv, pred_s_inv))

print("LSTM Suhu - MAE:", mae_s)
print("LSTM Suhu - RMSE:", rmse_s)

model_angin = Sequential([
    LSTM(64, return_sequences=False, input_shape=(WINDOW, 1)),
    Dropout(0.3),
    Dense(1)
])

model_angin.compile(
    optimizer='adam',
    loss='mse'
)

history_a = model_angin.fit(
    X_train_a, y_train_a,
    validation_data=(X_val_a, y_val_a),
    epochs=100,
    batch_size=64,
    callbacks=[early_stop],
    verbose=1
)

pred_a = model_angin.predict(X_test_a)

y_test_a_inv = scaler_angin.inverse_transform(y_test_a.reshape(-1,1))
pred_a_inv = scaler_angin.inverse_transform(pred_a)

mae_a = mean_absolute_error(y_test_a_inv, pred_a_inv)
rmse_a = np.sqrt(mean_squared_error(y_test_a_inv, pred_a_inv))

print("LSTM Angin - MAE:", mae_a)
print("LSTM Angin - RMSE:", rmse_a)

plt.figure(figsize=(14,4))
plt.plot(y_test_s_inv[:200], label='Actual')
plt.plot(pred_s_inv[:200], label='Predicted')
plt.title("LSTM Suhu – Actual vs Predicted")
plt.legend()
plt.show()

plt.figure(figsize=(14,4))
plt.plot(y_test_a_inv[:200], label='Actual')
plt.plot(pred_a_inv[:200], label='Predicted')
plt.title("LSTM Kecepatan Angin – Actual vs Predicted")
plt.legend()
plt.show()